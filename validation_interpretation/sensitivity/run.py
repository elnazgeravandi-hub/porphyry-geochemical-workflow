"""Fixed-configuration data-treatment comparisons, followed by optional separate reoptimization.

Alternative concentrations must be generated by documented, authorized scenarios;
this command does not invent thresholds or infer laboratory codes.
"""
import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
from threadpoolctl import threadpool_limits
from common.io import read_indexed,load_labels
from common.integrity import verify_model_input
from data_preparation.run import UNITS
from common.core import ELEMENTS,prepare,metrics,describe
from common.partition_evaluation import agreement
from validation_interpretation.stability.run import make_refit
from common.io import save
from workflow.run import run


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--primary-input',required=True)
    parser.add_argument('--models',required=True);parser.add_argument('--scenarios',required=True)
    parser.add_argument('--output',required=True);parser.add_argument('--reoptimize-config')
    args=parser.parse_args()
    verify_model_input(args.primary_input,args.models)
    primary=read_indexed(args.primary_input)[ELEMENTS]
    labels=load_labels(args.models,primary.index)
    scaler=json.loads((Path(args.models)/'preprocessing.json').read_text())
    specifications=json.loads(Path(args.scenarios).read_text())['scenarios']
    out=Path(args.output);out.mkdir(parents=True,exist_ok=False);rows=[];names=set()
    for specification in specifications:
        name=specification['name']
        if not isinstance(name,str) or not name.isidentifier() or name in names:raise ValueError('Unique identifier-like scenario names required.')
        names.add(name)
        if not specification.get('scientific_basis'):raise ValueError('Document every scenario.')
        alternative=read_indexed(specification['processed_input'])[ELEMENTS]
        if set(alternative.index)!=set(primary.index):raise ValueError('All scenarios must have exactly matching sample IDs.')
        alternative=alternative.loc[primary.index]
        scaling=specification['scaling_mode']
        if scaling=='refit_common':z,_=prepare(alternative.reset_index(),UNITS)
        elif scaling=='fixed_primary':
            x=alternative.to_numpy(float).copy();x[:,1]/=1000
            if not np.isfinite(x).all() or (x<=0).any():raise ValueError('Positive processed scenario concentrations required.')
            logs=np.log(x);clr=logs-logs.mean(axis=1,keepdims=True)
            z=(clr-np.asarray(scaler['median']))/np.asarray(scaler['iqr'])
        else:raise ValueError('Declare fixed_primary or refit_common scaling.')
        for model_name,reference in labels.items():
            selected=json.loads((Path(args.models)/f'{model_name}_selected.json').read_text())
            prediction=make_refit(model_name.split('_')[0],selected)(z)
            try:scores=metrics(z,prediction,complementary=True);status='valid'
            except ValueError:scores={};status='invalid_metric_partition'
            rows.append({'scenario':name,'model':model_name,'scaling_mode':scaling,'status':status,
                **describe(prediction),**agreement(reference,prediction),**scores})
        # Keep the fixed-configuration evaluation distinct from a new optimizer search.
        if args.reoptimize_config:
            local=out/f'{name}_aligned_concentrations.csv';alternative.to_csv(local,index_label='sample_id')
            run(local,args.reoptimize_config,out/f'{name}_reoptimized')
    pd.DataFrame(rows).to_csv(out/'fixed_configuration_sensitivity.csv',index=False)
    save(out/'scenario_provenance.json',{'scenarios':specifications,'reoptimized':bool(args.reoptimize_config),
        'warning':'Separate reoptimization uses the primary workflow, including refitted scenario preprocessing, regardless of fixed-stage scaling_mode.'})

if __name__=='__main__':
    with threadpool_limits(limits=1):main()
